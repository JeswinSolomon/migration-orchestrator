"""Profiles the legacy CSVs and prints a data-quality report."""
import re
from pathlib import Path

import pandas as pd

DATA = Path(__file__).parent / "data"
REPORT = Path(__file__).parent.parent / "docs" / "02-data-profile.md"
DATE_PATTERNS = {
    "ISO yyyy-mm-dd": r"^\d{4}-\d{2}-\d{2}$",
    "US mm/dd/yyyy": r"^\d{2}/\d{2}/\d{4}$",
    "dd-Mon-yy": r"^\d{2}-[A-Za-z]{3}-\d{2}$",
}
lines = ["# Legacy Data Profile (generated by legacy-data/profile_legacy_data.py)\n"]


def add(title, rows):
    lines.append(f"\n## {title}\n")
    lines.extend(f"- {r}" for r in rows)


def date_formats(series):
    s = series.fillna("").astype(str)
    out = [f"{name}: {s.str.match(p).sum()}" for name, p in DATE_PATTERNS.items()]
    out.append(f"empty: {(s == '').sum()}")
    return out


b = pd.read_csv(DATA / "borrowers.csv", dtype=str, encoding="latin-1", keep_default_na=False)
l = pd.read_csv(DATA / "loans.csv", dtype=str, encoding="latin-1", keep_default_na=False)
p = pd.read_csv(DATA / "payments.csv", dtype=str, encoding="latin-1", keep_default_na=False)

add("Row counts", [f"borrowers={len(b)}, loans={len(l)}, payments={len(p)}"])

dup_key = b["full_name"].str.lower()
dups = b[dup_key.duplicated(keep=False) & (b["email"] == "")]
add("Borrowers", [
    f"missing email: {(b.email == '').sum()}",
    f"missing phone: {(b.phone == '').sum()}",
    "phone formats: " + str(b.phone.map(lambda x: re.sub(r"\d", "9", x)).value_counts().to_dict()),
    "dob formats: " + ", ".join(date_formats(b.dob)),
    f"ALL-CAPS names (inconsistent casing): {(b.full_name == b.full_name.str.upper()).sum()}",
    f"likely duplicate records (same name, no email, id > {len(b) - 100}): {int((b.borrower_id.astype(int) > 5000).sum())}",
])

orphans = l[~l.borrower_id.isin(b.borrower_id)]
add("Loans", [
    f"orphan loans (borrower not found): {len(orphans)}",
    "rate_pct values: " + str(l.rate_pct.value_counts().to_dict()),
    "status values: " + str(l.status.value_counts().to_dict()),
    f"missing balance: {(l.balance == '').sum()}",
    "start_date formats: " + ", ".join(date_formats(l.start_date)),
])

amt = pd.to_numeric(p.amount, errors="coerce")
add("Payments", [
    f"negative amounts (refunds or errors?): {(amt < 0).sum()}",
    f"orphan payments (loan not found): {(~p.loan_id.isin(l.loan_id)).sum()}",
    "paid_on formats: " + ", ".join(date_formats(p.paid_on)),
    f"total sum: {amt.sum():.2f}",
])

REPORT.write_text("\n".join(lines) + "\n", encoding="utf-8")
print("\n".join(lines))
